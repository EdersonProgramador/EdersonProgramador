export type EnemCronogramaLesson = {
  slug: string;
  title: string;
  lessonType?: "article";
  bodyHtml?: string;
  sectionTitle: string;
  sectionSortOrder: number;
};

export type EnemCronogramaModule = {
  title: string;
  lessons: EnemCronogramaLesson[];
};

export type EnemCronogramaCatalog = {
  slug: string;
  title: string;
  summary: string;
  coverUrl?: string;
  sortOrder: number;
  catalogVersion: number;
  modules: EnemCronogramaModule[];
};

function escapeHtml(text: string) {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function slugify(title: string) {
  return title
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 52);
}

function cronogramaLesson(
  moduleKey: string,
  index: number,
  sectionTitle: string,
  sectionSortOrder: number,
  title: string,
  extraHtml = ""
): EnemCronogramaLesson {
  const slug = `${moduleKey}-${String(index + 1).padStart(3, "0")}-${slugify(title)}`.slice(0, 80);
  const bodyHtml = `<p class="course-text-muted text-sm">Cronograma <strong>ENEM — Felipe Araújo</strong> · ${escapeHtml(sectionTitle)}</p>
<h3>${escapeHtml(title)}</h3>
${extraHtml}
<p>Siga a mesma rotina da folha oficial para este tópico:</p>
<ol class="text-sm">
<li>Aula ou leitura</li>
<li>Resumo</li>
<li>Exercícios</li>
<li>Revisão</li>
</ol>
<p>Marque a aula como concluída quando encerrar o ciclo deste tópico.</p>`;
  return {
    slug,
    title,
    lessonType: "article",
    bodyHtml,
    sectionTitle,
    sectionSortOrder
  };
}

function buildLessons(
  moduleKey: string,
  sections: { sectionTitle: string; sectionSortOrder: number; topics: string[]; extraForTopic?: Record<string, string> }[]
): EnemCronogramaLesson[] {
  const lessons: EnemCronogramaLesson[] = [];
  let index = 0;
  for (const sec of sections) {
    for (const title of sec.topics) {
      const extra = sec.extraForTopic?.[title] ?? "";
      lessons.push(cronogramaLesson(moduleKey, index++, sec.sectionTitle, sec.sectionSortOrder, title, extra));
    }
  }
  return lessons;
}

/** Uma folha do cronograma = um módulo; cada linha = uma aula (sectionTitle igual ao módulo → TOC plano). */
function cronogramaModule(
  moduleKey: string,
  title: string,
  topics: string[],
  extraForTopic?: Record<string, string>
): EnemCronogramaModule {
  return {
    title,
    lessons: buildLessons(moduleKey, [{ sectionTitle: title, sectionSortOrder: 1, topics, extraForTopic }])
  };
}

